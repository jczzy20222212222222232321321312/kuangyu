'use strict';
const fs=require('fs'),path=require('path'),{ethers}=require('ethers');
const root=path.join(__dirname,'..');
const RPC=process.env.BSC_TESTNET_RPC||'https://bsc-testnet-rpc.publicnode.com';
const key=JSON.parse(fs.readFileSync('/Users/panda2/Documents/deepseek-harness/default-workspace/.ore-secrets/signer.json','utf8')).privateKey;
const art=n=>JSON.parse(fs.readFileSync(path.join(root,'build',n+'.json'),'utf8'));
const ORE='0xa7a339C8E75B19669af2C9D3596C8B4f721c424d', NFT='0xFACb3f4f34C9B4a40EE57Eaa0179cA5030363708';
(async()=>{const p=new ethers.JsonRpcProvider(RPC,97,{staticNetwork:true});const w=new ethers.Wallet(key,p);console.log('signer',w.address,ethers.formatEther(await p.getBalance(w.address)));
 const dep=async(name,args)=>{const a=art(name);const f=new ethers.ContractFactory(a.abi,a.bytecode,w);const c=await f.deploy(...args);const tx=c.deploymentTransaction();await c.waitForDeployment();const addr=await c.getAddress();console.log(name,addr,tx.hash);return {c,addr,tx:tx.hash};};
 const vault=await dep('OreVault',[ORE,w.address]);
 const pool=await dep('OreMinePool',[ORE,w.address]);
 const burner=await dep('OreBurner',[NFT]);
 const market=await dep('OreMarket',[ORE,NFT]);
 const token=new ethers.Contract(ORE,['function transfer(address,uint256)'],w);
 let tx=await token.transfer(pool.addr,80_000_000n*10n**18n);await tx.wait();console.log('pool funded');
 tx=await token.transfer(vault.addr,10_000_000n*10n**18n);await tx.wait();console.log('vault funded');
 const out={chainId:97,deployedAt:new Date().toISOString(),signer:w.address,ore:ORE,nft:NFT,vault:vault.addr,minePool:pool.addr,burner:burner.addr,market:market.addr,tx:{vault:vault.tx,pool:pool.tx,burner:burner.tx,market:market.tx}};
 fs.writeFileSync(path.join(root,'build','deployment-new.json'),JSON.stringify(out,null,2));console.log(JSON.stringify(out,null,2));
})().catch(e=>{console.error(e.shortMessage||e.message||e);process.exit(1)});
